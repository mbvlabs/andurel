type sequentialReader struct {
	data []byte
	pos  int
}

func (r *sequentialReader) Read(p []byte) (int, error) {
	if r.pos >= len(r.data) {
		return 0, io.EOF
	}
	n := copy(p, r.data[r.pos:])
	r.pos += n
	return n, nil
}

// Enabled reports whether this binary was built with the andurel_golden tag.
func Enabled() bool {
	return true
}

// RandomReader returns a deterministic reader for scaffold secrets.
func RandomReader() io.Reader {
	return &sequentialReader{data: seedMaterial}
}

// Now returns the locked golden clock.
func Now() time.Time {
	return FixedTime
}
