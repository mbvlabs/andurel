const generatedRoutesJSPath = "resources/js/routes.ts"

type routesJSReport struct {
	GeneratedFile    string                 `json:"generated_file"`
	GeneratedHelpers int                    `json:"generated_helpers"`
	SkippedCount     int                    `json:"skipped_count"`
	Skipped          []routeManifestSkipped `json:"skipped,omitempty"`
}

type routeJSHelper struct {
	Name  string
	Route routeManifestRoute
}

func newGenerateRoutesCommand() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "routes",
		Short: "Generate TypeScript route helpers for Inertia frontends",
		Long: `Generate framework-neutral TypeScript route helpers for Inertia frontends.

The command reads routes/*.go as the source of truth and writes
resources/js/routes.ts for Vue, React, or Svelte Inertia frontends. A route
opts in with routing.TypeScriptRoute() (routing.InertiaRoute() is a deprecated
alias), so JSON endpoints and asset URLs can get typed helpers too.

A full-URL helper throws until origins are configured: browser entries call
configureRouteHosts at boot and SSR entries wrap each render in
withRouteHosts. Use routes.<name>.path() for a relative URL.`,
		Example: `  andurel sync routes
  andurel sync routes --json`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			rootDir, err := findGoModRoot()
			if err != nil {
				return err
			}
			if err := requireInertiaProjectForRoutesJS(rootDir); err != nil {
				return err
			}
			manifest, err := collectRouteManifest(rootDir)
			if err != nil {
				return err
			}
			report, err := generateRoutesJSFile(rootDir, manifest)
			if err != nil {
				return err
			}
			return output.OK(cmd, report, routesJSReportSummary(report))
		},
	}
	setAgentMetadata(
		cmd,
		"generation",
		"Writes Inertia frontend route helpers to resources/js/routes.ts from the route manifest. Use --json for generated helper and skipped counts.",
	)
	return cmd
}

func requireInertiaProjectForRoutesJS(rootDir string) error {
	_, err := configuredInertiaAdapter(rootDir)
	return err
}

func configuredInertiaAdapter(rootDir string) (string, error) {
	adapter, err := projectUIAdapter(rootDir)
	if err != nil {
		return "", err
	}
	if adapter == "" {
		return "", output.NewError(
			output.CodeInvalidInertiaAdapter,
			"this operation requires an Inertia project",
			output.ExitUsage,
			"Create the project with --ui react/pnpm, --ui vue/bun, or --ui svelte/npm before generating Inertia artifacts.",
		)
	}
	return adapter, nil
}

// projectUIAdapter returns the Inertia adapter from andurel.lock, or "" when
// the project has no Inertia adapter configured.
func projectUIAdapter(rootDir string) (string, error) {
	lock, err := layout.ReadLockFile(rootDir)
	if err != nil {
		return "", output.WrapError(
			output.CodeConfigError,
			err,
			output.ExitConfig,
			"Run this from an Andurel project with andurel.lock.",
		)
	}
	if lock.ScaffoldConfig == nil || lock.ScaffoldConfig.Inertia == "" {
		return "", nil
	}
	if !layout.IsSupportedInertiaAdapter(lock.ScaffoldConfig.Inertia) {
		return "", output.NewError(
			output.CodeInvalidInertiaAdapter,
			fmt.Sprintf(
				"unsupported inertia adapter in andurel.lock: %s",
				lock.ScaffoldConfig.Inertia,
			),
			output.ExitUsage,
			"Use vue, react, or svelte in scaffoldConfig.inertia before generating Inertia artifacts.",
		)
	}
	return lock.ScaffoldConfig.Inertia, nil
}

func generateRoutesJSFile(rootDir string, manifest routeManifest) (routesJSReport, error) {
	content, helperCount, err := renderRoutesJS(manifest)
	if err != nil {
		return routesJSReport{}, err
	}

	target := filepath.Join(rootDir, generatedRoutesJSPath)
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return routesJSReport{}, err
	}
	if err := os.WriteFile(target, content, 0o644); err != nil {
		return routesJSReport{}, err
	}

	return routesJSReport{
		GeneratedFile:    generatedRoutesJSPath,
		GeneratedHelpers: helperCount,
		SkippedCount:     len(manifest.Skipped),
		Skipped:          append([]routeManifestSkipped(nil), manifest.Skipped...),
	}, nil
}

func routesJSReportSummary(report routesJSReport) string {
	summary := fmt.Sprintf(
		"Generated %d route helpers to %s",
		report.GeneratedHelpers,
		report.GeneratedFile,
	)
	if report.SkippedCount > 0 {
		summary = fmt.Sprintf("%s (%d skipped)", summary, report.SkippedCount)
	}
	return summary
}

const routesJSPreamble = `// Code generated by andurel; DO NOT EDIT.
//
// Helpers are generated for routes marked routing.TypeScriptRoute()
// (routing.InertiaRoute() is a deprecated alias).
//
// A full-URL helper needs configured origins. Browser entries call
// configureRouteHosts once at boot from the shared hosts prop; SSR entries call
// withRouteHosts around each render so concurrent requests never share origin
// state. Calling a full-URL helper before configuration throws: a module-scope
// const evaluated at import would otherwise freeze an empty or stale origin.
// Use routes.<name>.path() when only a relative URL is needed; .path() and
// .host work without configuration.

type HostOrigins = Record<string, string>

/** Host origins for one render. SSR entries register a request-scoped scope. */
export type RouteHostScope = {
  current: () => HostOrigins | undefined
  run: <T>(hosts: HostOrigins, render: () => T) => T
}

let configuredOrigins: HostOrigins | null = null
let routeHostScope: RouteHostScope | null = null

/** Call once at browser boot with the Inertia shared hosts prop. */
export function configureRouteHosts(next: HostOrigins) {
  configuredOrigins = next
}

/** Install the request-scoped host context used by the SSR entry. */
export function configureRouteHostScope(scope: RouteHostScope | null) {
  routeHostScope = scope
}

/** Run one SSR render with its own host origins. */
export function withRouteHosts<T>(hosts: HostOrigins, render: () => T): T {
  if (routeHostScope === null) {
    throw new Error(
      'routes: withRouteHosts requires configureRouteHostScope(...) in the SSR entry, for example resources/js/ssr.ts',
    )
  }
  return routeHostScope.run(hosts, render)
}

function currentOrigins(): HostOrigins {
  const scoped = routeHostScope?.current()
  const origins = scoped ?? configuredOrigins
  if (origins === null || origins === undefined) {
    throw new Error(
      'routes: route hosts are not configured yet; call configureRouteHosts(...) at boot or withRouteHosts(...) per SSR render, or use routes.<name>.path() for a relative URL',
    )
  }
  return origins
}

function origin(host: string): string {
  const origins = currentOrigins()
  const resolved = origins[host] ?? origins.primary
  if (resolved === undefined || resolved === '') {
    throw new Error(
      'routes: no origin configured for route host "' + host + '"; add it to the shared hosts prop or use routes.<name>.path()',
    )
  }
  return resolved
}

export const routes = {
`

const routesJSHelperRuntime = `
function routeHelper<Args extends unknown[]>(def: {
  host: string
  path: (...args: Args) => string
}) {
  const full = (...args: Args) => origin(def.host) + def.path(...args)
  return Object.assign(full, {
    path: def.path,
    host: def.host,
  })
}
`

func renderRoutesJS(manifest routeManifest) ([]byte, int, error) {
	helpers, err := routeJSHelpers(manifest.Routes)
	if err != nil {
		return nil, 0, err
	}

	var buf bytes.Buffer
	buf.WriteString(routesJSPreamble)
	for _, helper := range helpers {
		line, err := renderRouteJSHelper(helper)
		if err != nil {
			return nil, 0, err
		}
		buf.WriteString("  ")
		buf.WriteString(line)
		buf.WriteString(",\n")
	}
	buf.WriteString("}\n")
	buf.WriteString(routesJSHelperRuntime)

	return buf.Bytes(), len(helpers), nil
}

func routeJSHelpers(routes []routeManifestRoute) ([]routeJSHelper, error) {
	helpers := make([]routeJSHelper, 0, len(routes))
	seen := map[string]routeManifestRoute{}
	for _, route := range routes {
		if !shouldGenerateRouteJSHelper(route) {
			continue
		}
		helperName := naming.ToLowerCamelCase(route.Variable)
		if existing, ok := seen[helperName]; ok {
			return nil, output.NewError(
				output.CodeGenerationFailed,
				fmt.Sprintf(
					"route helper name collision for %q: %s and %s both map to %s",
					helperName,
					existing.Variable,
					route.Variable,
					helperName,
				),
				output.ExitGeneration,
				"Rename one route variable so generated TypeScript helper names are unique.",
			)
		}
		if err := validateRouteJSParams(route); err != nil {
			return nil, err
		}
		seen[helperName] = route
		helpers = append(helpers, routeJSHelper{Name: helperName, Route: route})
	}
	slices.SortStableFunc(helpers, func(a, b routeJSHelper) int {
		return strings.Compare(a.Name, b.Name)
	})
	return helpers, nil
}

// shouldGenerateRouteJSHelper reports whether a route opted in with
// routing.TypeScriptRoute() (recorded as IsInertia for manifest compatibility).
func shouldGenerateRouteJSHelper(route routeManifestRoute) bool {
	return route.IsInertia
}

func validateRouteJSParams(route routeManifestRoute) error {
	seen := map[string]struct{}{}
	for _, param := range route.Params {
		if !isTypeScriptIdentifier(param.Name) {
			return output.NewError(
				output.CodeGenerationFailed,
				fmt.Sprintf(
					"route %s has parameter %q that cannot be used as a TypeScript identifier",
					route.Variable,
					param.Name,
				),
				output.ExitGeneration,
				"Rename the route parameter to a valid identifier before generating TypeScript helpers.",
			)
		}
		if _, ok := seen[param.Name]; ok {
			return output.NewError(
				output.CodeGenerationFailed,
				fmt.Sprintf("route %s repeats parameter %q", route.Variable, param.Name),
				output.ExitGeneration,
				"Use unique parameter names in each route path before generating TypeScript helpers.",
			)
		}
		seen[param.Name] = struct{}{}
	}
	return nil
}

func renderRouteJSHelper(helper routeJSHelper) (string, error) {
	route := helper.Route
	host := routeJSHost(route)
	path := routeJSURLPath(route)
	args := make([]string, 0, len(route.Params))
	for _, param := range route.Params {
		args = append(args, fmt.Sprintf("%s: %s", param.Name, routeJSType(param.Type)))
	}

	var pathExpr string
	if len(route.Params) == 0 {
		pathExpr = fmt.Sprintf("() => '%s'", escapeTSSingleQuoted(path))
	} else {
		renderedPath, err := renderRouteJSTemplatePath(route)
		if err != nil {
			return "", err
		}
		pathExpr = fmt.Sprintf("(%s) => `%s`", strings.Join(args, ", "), renderedPath)
	}

	return fmt.Sprintf(
		"%s: routeHelper({\n    host: '%s',\n    path: %s,\n  })",
		helper.Name,
		escapeTSSingleQuoted(host),
		pathExpr,
	), nil
}

// routeJSURLPath is the URL path a generated helper returns. Exact routes keep
// their ServeMux pattern ("/{$}") separately; helpers must only emit the URL.
func routeJSURLPath(route routeManifestRoute) string {
	return strings.TrimSuffix(route.Path, "{$}")
}

func routeJSHost(route routeManifestRoute) string {
	if route.Host == "" {
		return "primary"
	}
	return route.Host
}

func renderRouteJSTemplatePath(route routeManifestRoute) (string, error) {
	paramSet := map[string]struct{}{}
	for _, param := range route.Params {
		paramSet[param.Name] = struct{}{}
	}

	segments := strings.Split(routeJSURLPath(route), "/")
	for i, segment := range segments {
		if !strings.HasPrefix(segment, ":") {
			segments[i] = escapeTSTemplateStatic(segment)
			continue
		}
		name := strings.TrimPrefix(segment, ":")
		if _, ok := paramSet[name]; !ok {
			return "", output.NewError(
				output.CodeGenerationFailed,
				fmt.Sprintf(
					"route %s path references parameter %q missing from manifest params",
					route.Variable,
					name,
				),
				output.ExitGeneration,
				"Inspect the route manifest and route path before generating TypeScript helpers.",
			)
		}
		segments[i] = "${" + name + "}"
	}
	return strings.Join(segments, "/"), nil
}

func routeJSType(manifestType string) string {
	switch manifestType {
	case "int32", "int64":
		return "number"
	case "uuid", "string":
		return "string"
	default:
		return "string"
	}
}

func escapeTSSingleQuoted(value string) string {
	value = strings.ReplaceAll(value, "\\", "\\\\")
	value = strings.ReplaceAll(value, "'", "\\'")
	value = strings.ReplaceAll(value, "\n", "\\n")
	value = strings.ReplaceAll(value, "\r", "\\r")
	return value
}

func escapeTSTemplateStatic(value string) string {
	value = strings.ReplaceAll(value, "\\", "\\\\")
	value = strings.ReplaceAll(value, "`", "\\`")
	value = strings.ReplaceAll(value, "${", "\\${")
	return value
}

func isTypeScriptIdentifier(value string) bool {
	if value == "" {
		return false
	}
	for i, r := range value {
		if i == 0 {
			if r != '_' && r != '$' && !unicode.IsLetter(r) {
				return false
			}
			continue
		}
		if r != '_' && r != '$' && !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			return false
		}
	}
	return true
}
