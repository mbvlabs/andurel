const generatedTestMainHeader = "// Code generated by 'go test'. DO NOT EDIT."

type testCacheLayout struct {
	name string
	dir  string
}

func testCacheLayouts(t *testing.T, root string) []testCacheLayout {
	t.Helper()
	return []testCacheLayout{
		{name: "default"},
		{name: "fresh-external", dir: filepath.Join(t.TempDir(), "go-build")},
		{name: "internal-gocache-fresh", dir: filepath.Join(root, ".gocache-fresh")},
		{name: "internal-cache-go-build", dir: filepath.Join(root, ".cache", "go-build")},
	}
}

func writeGoFixture(t *testing.T, files map[string]string) string {
	t.Helper()
	return writeGoFixtureAt(t, t.TempDir(), files)
}

func writeGoFixtureAt(t *testing.T, root string, files map[string]string) string {
	t.Helper()
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatalf("create %s: %v", path, err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
	}
	return root
}

func scopeName(patterns []string) string {
	if len(patterns) == 0 {
		return "whole-project"
	}
	return strings.Join(patterns, ",")
}

func syntheticMainPackage(file string) *packages.Package {
	return &packages.Package{
		Name:    "main",
		PkgPath: "example.com/repro/payloads.test",
		GoFiles: []string{file},
	}
}

func checkPayloadViolations(t *testing.T, root string, patterns, want []string) {
	t.Helper()
	violations, err := AnalyzePatternsRules(root, patterns, []string{"payloads-import"})
	if err != nil {
		t.Fatalf("patterns %v: %v", patterns, err)
	}
	remaining := make(map[string]bool, len(want))
	for _, file := range want {
		remaining[file] = true
	}
	for _, violation := range violations {
		if !remaining[violation.File] {
			t.Errorf("patterns %v: unexpected violation: %+v", patterns, violation)
			continue
		}
		delete(remaining, violation.File)
		if violation.Line == 0 {
			t.Errorf("patterns %v: violation has no source line: %+v", patterns, violation)
		}
	}
	for file := range remaining {
		t.Errorf("patterns %v: missing violation for %s", patterns, file)
	}
}

func TestPayloadTestMainIsNotProjectSource(t *testing.T) {
	root := writeGoFixture(t, map[string]string{
		"go.mod":                    "module example.com/repro\n\ngo 1.27.3\n",
		"payloads/payload.go":       "package payloads\n\ntype Message struct{}\n",
		"payloads/payload_test.go":  "package payloads\n\nimport \"testing\"\n\nfunc TestMessage(t *testing.T) {}\n",
		"payloads/external_test.go": "package payloads_test\n\nimport \"testing\"\n\nfunc TestExternal(t *testing.T) {}\n",
	})
	for _, cache := range testCacheLayouts(t, root) {
		t.Run(cache.name, func(t *testing.T) {
			if cache.dir != "" {
				t.Setenv("GOCACHE", cache.dir)
			}
			for _, patterns := range [][]string{nil, {"./payloads/..."}} {
				t.Run(scopeName(patterns), func(t *testing.T) {
					checkPayloadViolations(t, root, patterns, nil)
				})
			}
		})
	}
}

func TestPayloadTestMainPreservesProjectViolations(t *testing.T) {
	base := t.TempDir()
	root := writeGoFixtureAt(t, filepath.Join(base, "project"), map[string]string{
		"go.mod":                       "module example.com/repro\n\ngo 1.27.3\n",
		"payloads/payload.go":          "package payloads\n",
		"payloads/generated_source.go": "// Code generated by tool. DO NOT EDIT.\n\npackage payloads\n\nimport _ \"net/http\"\n",
		"payloads/internal_test.go":    "package payloads\n\nimport _ \"net/http\"\n",
		"payloads/external_test.go":    "package payloads_test\n\nimport _ \"net/http\"\n",
		"payloads/nested/invalid.go":   "package nested\n\nimport _ \"net/http\"\n",
		"payloads/runner.test/main.go": generatedTestMainHeader + "\n\npackage main\n\nimport _ \"net/http\"\n\nfunc main() {}\n",
	})
	caches := []testCacheLayout{
		{name: "default"},
		{name: "cache-at-project-root", dir: root},
		{name: "cache-above-project-root", dir: base},
	}
	for _, cache := range caches {
		t.Run(cache.name, func(t *testing.T) {
			if cache.dir != "" {
				t.Setenv("GOCACHE", cache.dir)
			}
			for _, tc := range []struct {
				patterns []string
				want     []string
			}{
				{
					patterns: nil,
					want: []string{
						"payloads/generated_source.go",
						"payloads/internal_test.go",
						"payloads/external_test.go",
						"payloads/nested/invalid.go",
						"payloads/runner.test/main.go",
					},
				},
				{
					patterns: []string{"./payloads"},
					want: []string{
						"payloads/generated_source.go",
						"payloads/internal_test.go",
						"payloads/external_test.go",
					},
				},
			} {
				t.Run(scopeName(tc.patterns), func(t *testing.T) {
					checkPayloadViolations(t, root, tc.patterns, tc.want)
				})
			}
		})
	}
}

func TestPinnedGoSyntheticTestMainUsesCacheDataArtifact(t *testing.T) {
	root := writeGoFixture(t, map[string]string{
		"go.mod":                    "module example.com/repro\n\ngo 1.27.3\n",
		"payloads/payload.go":       "package payloads\n\ntype Message struct{}\n",
		"payloads/payload_test.go":  "package payloads\n\nimport \"testing\"\n\nfunc TestMessage(t *testing.T) {}\n",
		"payloads/external_test.go": "package payloads_test\n\nimport \"testing\"\n\nfunc TestExternal(t *testing.T) {}\n",
	})
	cacheDir, err := goEnvValue(root, "GOCACHE")
	if err != nil {
		t.Fatalf("go env GOCACHE: %v", err)
	}
	if cacheDir == "" || cacheDir == "off" {
		t.Fatalf("go env GOCACHE = %q", cacheDir)
	}
	loaded, err := packages.Load(&packages.Config{
		Mode:  packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles,
		Dir:   root,
		Tests: true,
	}, "./payloads/...")
	if err != nil {
		t.Fatalf("load packages: %v", err)
	}
	var synthetic *packages.Package
	for _, pkg := range loaded {
		if pkg.Name == "main" && strings.HasSuffix(pkg.PkgPath, ".test") {
			synthetic = pkg
			break
		}
	}
	if synthetic == nil {
		t.Fatalf("go list -test did not report a synthetic test main: %+v", loaded)
	}
	if synthetic.ForTest != "" {
		t.Fatalf("synthetic test main ForTest = %q, want empty", synthetic.ForTest)
	}
	if len(synthetic.GoFiles) != 1 {
		t.Fatalf("synthetic test main GoFiles = %v, want one cache artifact", synthetic.GoFiles)
	}
	file := synthetic.GoFiles[0]
	if !isGoCacheDataFile(cacheDir, file) {
		t.Fatalf("pinned go synthetic main %q is not a cache data artifact under %q", file, cacheDir)
	}
	data, err := os.ReadFile(file)
	if err != nil {
		t.Fatalf("read synthetic test main: %v", err)
	}
	if !strings.HasPrefix(strings.TrimSpace(string(data)), goTestMainHeader) {
		t.Fatalf("synthetic test main %q does not start with %q", file, goTestMainHeader)
	}
}

func TestTestMainCacheDirResolvesLazily(t *testing.T) {
	root := t.TempDir()
	calls := 0
	lookup := func(string, string) (string, error) {
		calls++
		return "  /cache/go-build\n", nil
	}
	ordinary := &packages.Package{
		Name:    "payloads",
		PkgPath: "example.com/repro/payloads",
		GoFiles: []string{"payload.go"},
	}
	cacheDir, ok := testMainCacheDir(root, []*packages.Package{ordinary}, lookup)
	if ok || cacheDir != "" || calls != 0 {
		t.Fatalf("non-candidate lookup = %q, %t, calls %d; want no lookup", cacheDir, ok, calls)
	}
	cacheDir, ok = testMainCacheDir(root, []*packages.Package{syntheticMainPackage("source")}, lookup)
	if !ok || cacheDir != "/cache/go-build" || calls != 1 {
		t.Fatalf("candidate lookup = %q, %t, calls %d; want trimmed cache path and one lookup", cacheDir, ok, calls)
	}
}

func TestTestMainCacheDirRejectsUnusableLookups(t *testing.T) {
	pkg := syntheticMainPackage("source")
	for _, tc := range []struct {
		name  string
		value string
		err   error
	}{
		{name: "command failure", err: errors.New("go unavailable")},
		{name: "empty"},
		{name: "whitespace", value: " \n\t"},
		{name: "off", value: "off"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			cacheDir, ok := testMainCacheDir(t.TempDir(), []*packages.Package{pkg}, func(string, string) (string, error) {
				return tc.value, tc.err
			})
			if ok || cacheDir != "" {
				t.Fatalf("unusable lookup = %q, %t; want no cache", cacheDir, ok)
			}
		})
	}
}

func TestIsGoCacheDataFile(t *testing.T) {
	cacheDir := t.TempDir()
	actionID := "ab" + strings.Repeat("0", 62)
	artifact := filepath.Join(cacheDir, actionID[:2], actionID+"-d")
	if err := os.MkdirAll(filepath.Dir(artifact), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name string
		path string
		want bool
	}{
		{name: "cache data artifact", path: artifact, want: true},
		{name: "ordinary go source", path: filepath.Join(cacheDir, "payloads", "runner.test", "main.go")},
		{name: "archive suffix", path: filepath.Join(cacheDir, actionID[:2], actionID+"-a")},
		{name: "short action id", path: filepath.Join(cacheDir, actionID[:2], "ab-d")},
		{name: "wrong prefix directory", path: filepath.Join(cacheDir, "ac", actionID+"-d")},
		{name: "extra directory level", path: filepath.Join(cacheDir, actionID[:2], "extra", actionID+"-d")},
		{name: "uppercase action id", path: filepath.Join(cacheDir, actionID[:2], strings.ToUpper(actionID)+"-d")},
		{name: "go extension", path: artifact + ".go"},
		{name: "outside cache", path: filepath.Join(t.TempDir(), actionID[:2], actionID+"-d")},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := isGoCacheDataFile(cacheDir, tc.path); got != tc.want {
				t.Fatalf("isGoCacheDataFile(%q) = %t, want %t", tc.path, got, tc.want)
			}
		})
	}
}

func TestIsGoCacheDataFileRejectsSymlinkEscape(t *testing.T) {
	cacheDir := t.TempDir()
	actionID := "cd" + strings.Repeat("1", 62)
	outside := filepath.Join(t.TempDir(), "main.go")
	if err := os.WriteFile(outside, []byte(generatedTestMainHeader+"\n\npackage main\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	artifact := filepath.Join(cacheDir, actionID[:2], actionID+"-d")
	if err := os.MkdirAll(filepath.Dir(artifact), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, artifact); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	if pathWithinDir(cacheDir, artifact) {
		t.Fatalf("pathWithinDir accepted symlink escape %s -> %s", artifact, outside)
	}
	if isGoCacheDataFile(cacheDir, artifact) {
		t.Fatalf("isGoCacheDataFile accepted symlink escape %s -> %s", artifact, outside)
	}
}

func TestIsSyntheticTestMainRequiresGeneratedCacheDataAndHeader(t *testing.T) {
	cacheDir := t.TempDir()
	actionID := "ef" + strings.Repeat("2", 62)
	artifact := filepath.Join(cacheDir, actionID[:2], actionID+"-d")
	if err := os.MkdirAll(filepath.Dir(artifact), 0o755); err != nil {
		t.Fatal(err)
	}
	pkg := syntheticMainPackage(artifact)
	if isSyntheticTestMain(pkg, cacheDir) {
		t.Fatal("missing source accepted as synthetic test main")
	}
	if err := os.WriteFile(artifact, []byte("package main\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if isSyntheticTestMain(pkg, cacheDir) {
		t.Fatal("source without generated header accepted as synthetic test main")
	}
	if err := os.WriteFile(artifact, []byte(generatedTestMainHeader+"\n\npackage main\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !isSyntheticTestMain(pkg, cacheDir) {
		t.Fatal("valid generated cache data artifact rejected")
	}
	ordinary := filepath.Join(cacheDir, "payloads", "runner.test", "main.go")
	if err := os.MkdirAll(filepath.Dir(ordinary), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(ordinary, []byte(generatedTestMainHeader+"\n\npackage main\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if isSyntheticTestMain(syntheticMainPackage(ordinary), cacheDir) {
		t.Fatal("ordinary .test source inside the cache root accepted as synthetic test main")
	}
	unreadable := filepath.Join(cacheDir, "12", "12"+strings.Repeat("3", 62)+"-d")
	if err := os.MkdirAll(unreadable, 0o755); err != nil {
		t.Fatal(err)
	}
	if isSyntheticTestMain(syntheticMainPackage(unreadable), cacheDir) {
		t.Fatal("unreadable cache data path accepted as synthetic test main")
	}
}
