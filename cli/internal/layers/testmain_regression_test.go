package layers

import (
	"os"
	"path/filepath"
	"testing"
)

func TestPayloadTestMainIsNotProjectSource(t *testing.T) {
	root := t.TempDir()
	for name, content := range map[string]string{
		"go.mod":                    "module example.com/repro\n\ngo 1.27.3\n",
		"payloads/payload.go":       "package payloads\ntype Message struct{}\n",
		"payloads/payload_test.go":  "package payloads\nimport \"testing\"\nfunc TestMessage(t *testing.T) {}\n",
		"payloads/external_test.go": "package payloads_test\nimport \"testing\"\nfunc TestExternal(t *testing.T) {}\n",
	} {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
	}
	for _, patterns := range [][]string{nil, {"./payloads/..."}} {
		violations, err := AnalyzePatternsRules(root, patterns, []string{"payloads-import"})
		if err != nil {
			t.Fatal(err)
		}
		if len(violations) != 0 {
			t.Fatalf("patterns %v: unexpected violations: %+v", patterns, violations)
		}
	}
}

func TestPayloadTestMainPreservesProjectViolations(t *testing.T) {
	root := t.TempDir()
	for name, content := range map[string]string{
		"go.mod":                       "module example.com/repro\n\ngo 1.27.3\n",
		"payloads/payload.go":          "package payloads\n",
		"payloads/internal_test.go":    "package payloads\nimport _ \"net/http\"\n",
		"payloads/external_test.go":    "package payloads_test\nimport _ \"net/http\"\n",
		"payloads/nested/invalid.go":   "package nested\nimport _ \"net/http\"\n",
		"payloads/runner.test/main.go": "// Code generated by 'go test'. DO NOT EDIT.\npackage main\nimport _ \"net/http\"\nfunc main() {}\n",
	} {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
	}
	for _, tc := range []struct {
		patterns []string
		want     map[string]bool
	}{
		{nil, map[string]bool{"payloads/internal_test.go": true, "payloads/external_test.go": true, "payloads/nested/invalid.go": true, "payloads/runner.test/main.go": true}},
		{[]string{"./payloads"}, map[string]bool{"payloads/internal_test.go": true, "payloads/external_test.go": true}},
	} {
		violations, err := AnalyzePatternsRules(root, tc.patterns, []string{"payloads-import"})
		if err != nil {
			t.Fatal(err)
		}
		for _, violation := range violations {
			if !tc.want[violation.File] {
				t.Errorf("unexpected violation: %+v", violation)
			}
			delete(tc.want, violation.File)
		}
		if len(tc.want) != 0 {
			t.Errorf("missing violations: %v", tc.want)
		}
	}
}
