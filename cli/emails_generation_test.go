func TestScaffoldGeneratedEmailFilesMatchSyncEmails(t *testing.T) {
	rootDir := t.TempDir()
	if err := os.WriteFile(
		filepath.Join(rootDir, "go.mod"),
		[]byte("module example.com/app\n"),
		0o644,
	); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}

	for _, file := range []struct {
		template string
		target   string
	}{
		{template: "email_render_go.tmpl", target: "email/render.go"},
		{template: "email_verify_email.tmpl", target: "email/verify_email.go"},
		{template: "email_reset_password.tmpl", target: "email/reset_password.go"},
	} {
		content, err := fs.ReadFile(layouttemplates.Files, file.template)
		if err != nil {
			t.Fatalf("read layout template %s: %v", file.template, err)
		}
		target := filepath.Join(rootDir, filepath.FromSlash(file.target))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			t.Fatalf("mkdir for %s: %v", file.target, err)
		}
		if err := os.WriteFile(target, content, 0o644); err != nil {
			t.Fatalf("write %s: %v", file.target, err)
		}
	}

	props, manifest, count, err := renderEmailsTS(rootDir)
	if err != nil {
		t.Fatalf("render emails: %v", err)
	}
	if count != 2 {
		t.Fatalf("template count = %d, want 2", count)
	}

	for _, file := range []struct {
		template string
		got      []byte
	}{
		{template: "emails_generated_props_ts.tmpl", got: props},
		{template: "emails_generated_manifest_ts.tmpl", got: manifest},
	} {
		want, err := fs.ReadFile(layouttemplates.Files, file.template)
		if err != nil {
			t.Fatalf("read layout template %s: %v", file.template, err)
		}
		if string(file.got) != string(want) {
			t.Fatalf(
				"scaffold %s differs from sync emails output:\ngot:\n%s\nwant:\n%s",
				file.template,
				file.got,
				want,
			)
		}
	}
}

