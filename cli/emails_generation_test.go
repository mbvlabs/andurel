func TestRenderEmailsTSGolden(t *testing.T) {
	rootDir := setupPayloadsProject(t, "react")
	writePayloadsStructs(t, rootDir, "email/verify_email.go", `package email

type VerifyEmail struct {
	VerificationCode string
}

func (v VerifyEmail) ToHTML() (string, error) { return "", nil }

func (v VerifyEmail) ToText() (string, error) { return "", nil }
`)
	writePayloadsStructs(t, rootDir, "email/reset_password.go", `package email

type ResetPassword struct {
	ResetURL string
	Attempts int
	Score    float64
}

func (r *ResetPassword) ToHTML() (string, error) { return "", nil }

func (r *ResetPassword) ToText() (string, error) { return "", nil }
`)

	props, manifest, count, err := renderEmailsTS(rootDir)
	if err != nil {
		t.Fatalf("render emails: %v", err)
	}
	if count != 2 {
		t.Fatalf("template count = %d, want 2", count)
	}

	wantProps := `// Code generated by andurel sync emails; DO NOT EDIT.

// Edit the structs in email/*.go, then run andurel sync emails.
// Numeric Go fields are number | string: fixture data passes a number,
// while the generated template vars carry Go placeholder strings.

export type ResetPasswordProps = {
  ResetURL: string
  Attempts: number | string
  Score: number | string
}

export const ResetPasswordHtmlVars: ResetPasswordProps = {
  ResetURL: "{{.ResetURL | html}}",
  Attempts: "{{.Attempts | html}}",
  Score: "{{.Score | html}}",
}

export const ResetPasswordTextVars: ResetPasswordProps = {
  ResetURL: "{{.ResetURL}}",
  Attempts: "{{.Attempts}}",
  Score: "{{.Score}}",
}

export type VerifyEmailProps = {
  VerificationCode: string
}

export const VerifyEmailHtmlVars: VerifyEmailProps = {
  VerificationCode: "{{.VerificationCode | html}}",
}

export const VerifyEmailTextVars: VerifyEmailProps = {
  VerificationCode: "{{.VerificationCode}}",
}
`
	if string(props) != wantProps {
		t.Fatalf("unexpected props.ts:\n%s\nwant:\n%s", props, wantProps)
	}

	for _, want := range []string{
		`import ResetPassword from "../reset-password"`,
		`import VerifyEmail from "../verify-email"`,
		`name: "reset_password"`,
		`name: "verify_email"`,
		`component: ComponentType<ResetPasswordProps>`,
		"export const emails: EmailManifestEntry[] = [\n  resetPasswordTemplate,\n  verifyEmailTemplate,\n]",
	} {
		if !strings.Contains(string(manifest), want) {
			t.Errorf("manifest missing %q:\n%s", want, manifest)
		}
	}
}

func TestRenderEmailsTSSkipsStructsWithoutToHTML(t *testing.T) {
	rootDir := setupPayloadsProject(t, "react")
	writePayloadsStructs(t, rootDir, "email/emails.go", `package email

type NotAnEmail struct {
	Value string
}

type WrongSignature struct {
	Value string
}

type ValueReceiver struct {
	Value string
}

func (WrongSignature) ToHTML() string { return "" }

func (ValueReceiver) ToHTML() (string, error) { return "", nil }
`)

	props, manifest, count, err := renderEmailsTS(rootDir)
	if err != nil {
		t.Fatalf("render emails: %v", err)
	}
	if count != 1 {
		t.Fatalf("template count = %d, want 1", count)
	}
	if !strings.Contains(string(props), "export type ValueReceiverProps") {
		t.Fatalf("props.ts missing ValueReceiver:\n%s", props)
	}
	if strings.Contains(string(manifest), "NotAnEmail") ||
		strings.Contains(string(manifest), "WrongSignature") {
		t.Fatalf("manifest included a struct without ToHTML() (string, error):\n%s", manifest)
	}
}

func TestRenderEmailsTSRejectsUnsupportedFields(t *testing.T) {
	tests := []struct {
		name   string
		source string
		want   string
	}{
		{
			name: "slice",
			source: `package email
type BadEmail struct {
	Items []string
}
func (BadEmail) ToHTML() (string, error) { return "", nil }
`,
			want: "BadEmail.Items has unsupported type []string",
		},
		{
			name: "map",
			source: `package email
type BadEmail struct {
	Values map[string]string
}
func (BadEmail) ToHTML() (string, error) { return "", nil }
`,
			want: "BadEmail.Values has unsupported type map[string]string",
		},
		{
			name: "bool",
			source: `package email
type BadEmail struct {
	Enabled bool
}
func (BadEmail) ToHTML() (string, error) { return "", nil }
`,
			want: "BadEmail.Enabled has unsupported type bool",
		},
		{
			name: "pointer",
			source: `package email
type BadEmail struct {
	Name *string
}
func (BadEmail) ToHTML() (string, error) { return "", nil }
`,
			want: "BadEmail.Name has unsupported type *string",
		},
		{
			name: "embedded",
			source: `package email
type Base struct {
	Value string
}
type BadEmail struct {
	Base
}
func (BadEmail) ToHTML() (string, error) { return "", nil }
`,
			want: "BadEmail.(embedded) has unsupported type Base",
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			rootDir := setupPayloadsProject(t, "react")
			writePayloadsStructs(t, rootDir, "email/bad.go", test.source)
			_, _, _, err := renderEmailsTS(rootDir)
			if err == nil {
				t.Fatal("expected an unsupported field error")
			}
			if !strings.Contains(err.Error(), test.want) {
				t.Fatalf("error = %q, want it to contain %q", err, test.want)
			}
			var cliErr *output.CLIError
			if !errors.As(err, &cliErr) {
				t.Fatalf("error = %T, want *output.CLIError", err)
			}
			if !strings.Contains(
				cliErr.Hint,
				"Format it into a string field in Go (emails support scalar fields only).",
			) {
				t.Fatalf("error is missing the fix: %v", cliErr.Hint)
			}
		})
	}
}

