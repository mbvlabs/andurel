func setupPayloadsProject(t *testing.T, inertia string) string {
	t.Helper()
	rootDir := t.TempDir()
	if err := os.WriteFile(filepath.Join(rootDir, "go.mod"), []byte("module example.com/app\n"), 0o644); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}
	lock := layout.AndurelLock{
		SchemaVersion: 1,
		Version:       "test",
		Tools:         map[string]*layout.Tool{},
		ScaffoldConfig: &layout.ScaffoldConfig{
			ProjectName: "app",
			Inertia:     inertia,
		},
		DatabaseConfig: &layout.DatabaseConfig{
			Engine:   layout.DatabaseEnginePostgreSQL,
			NullType: layout.NullTypePGType,
		},
	}
	if err := lock.WriteLockFile(rootDir); err != nil {
		t.Fatalf("write project files: %v", err)
	}
	return rootDir
}

func writePayloadsStructs(t *testing.T, rootDir, rel, contents string) {
	t.Helper()
	path := filepath.Join(rootDir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
		t.Fatalf("write %s: %v", rel, err)
	}
}

