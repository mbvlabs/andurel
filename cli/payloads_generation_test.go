func TestRenderPayloadsTSRejectsUnmappablePayloads(t *testing.T) {
	tests := []struct {
		name   string
		source string
		want   string
	}{
		{
			name: "application import",
			source: `package payloads

import "example.com/app/domains"

type BadProps struct {
	Item domains.Widget ` + "`json:\"item\"`" + `
}
`,
			want: "may not import the app module",
		},
		{
			name: "net http import",
			source: `package payloads

import "net/http"

type BadProps struct {
	Method http.Handler ` + "`json:\"method\"`" + `
}
`,
			want: "may not depend on transport or persistence packages",
		},
		{
			name: "unmapped map",
			source: `package payloads

type BadProps struct {
	Values map[string]string ` + "`json:\"values\"`" + `
}
`,
			want: "unmapped type",
		},
		{
			name: "unexported nested struct",
			source: `package payloads

type hidden struct {
	Name string ` + "`json:\"name\"`" + `
}

type BadProps struct {
	Item hidden ` + "`json:\"item\"`" + `
}
`,
			want: "unmapped type",
		},
		{
			name: "type parameters",
			source: `package payloads

type PageProps[T any] struct {
	Item T ` + "`json:\"item\"`" + `
}
`,
			want: "uses type parameters",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rootDir := setupPayloadsProject(t, "vue")
			writePayloadsStructs(t, rootDir, "payloads/bad.go", tt.source)
			_, _, err := renderPayloadsTS(rootDir)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("error = %v, want %q", err, tt.want)
			}
		})
	}
}

