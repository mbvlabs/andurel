func TestCheckPayloadsTSGenerateFailsWhenMissingOrStale(t *testing.T) {
	rootDir := setupPayloadsProject(t, "vue")
	writePayloadsStructs(t, rootDir, "payloads/widgets.go", widgetPayloadsSource)

	missing := checkPayloadsTSGenerate(rootDir, false)
	if missing.status != statusFail || !strings.Contains(missing.message, "missing") {
		t.Fatalf("expected missing payloads.ts failure, got %#v", missing)
	}

	target := filepath.Join(rootDir, generatedPayloadsTSPath)
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatalf("create resources/js/types: %v", err)
	}
	if err := os.WriteFile(target, []byte("stale"), 0o644); err != nil {
		t.Fatalf("write stale payloads.ts: %v", err)
	}

	stale := checkPayloadsTSGenerate(rootDir, false)
	if stale.status != statusFail || !strings.Contains(stale.message, "out of date") {
		t.Fatalf("expected stale payloads.ts failure, got %#v", stale)
	}
	if !strings.Contains(strings.Join(stale.details, "\n"), "andurel sync payloads") {
		t.Fatalf("expected generate payloads hint, got %#v", stale)
	}
}

func TestCheckPayloadsTSGenerateLeavesPerResourceTypeFiles(t *testing.T) {
	rootDir := setupPayloadsProject(t, "svelte")
	writePayloadsStructs(t, rootDir, "payloads/widgets.go", widgetPayloadsSource)
	if _, err := generatePayloadsFile(rootDir); err != nil {
		t.Fatalf("generate payloads.ts: %v", err)
	}

	leftover := filepath.Join(rootDir, "resources", "js", "types", "widget.ts")
	want := []byte("export type LegacyWidget = { name: string }\n")
	if err := os.WriteFile(leftover, want, 0o644); err != nil {
		t.Fatalf("write leftover types file: %v", err)
	}

	result := checkPayloadsTSGenerate(rootDir, false)
	if result.status != statusPass {
		t.Fatalf("expected payloads.ts check to pass, got %#v", result)
	}
	got, err := os.ReadFile(leftover)
	if err != nil {
		t.Fatalf("leftover types file missing: %v", err)
	}
	if string(got) != string(want) {
		t.Fatalf("doctor mutated leftover per-resource types file:\n%s", got)
	}
}

