// TestRenderPayloadsTSScaffoldPayloadsPackage guards that the scaffold ships
// the auth request bodies and page props in payloads/, so sync payloads emits
// the types the auth pages pass to useForm and the welcome page receives.
func TestRenderPayloadsTSScaffoldPayloadsPackage(t *testing.T) {
	rootDir := setupPayloadsProject(t, "react")
	source, err := fs.ReadFile(layouttemplates.Files, "payloads_payloads.tmpl")
	if err != nil {
		t.Fatalf("read payloads_payloads.tmpl: %v", err)
	}
	writePayloadsStructs(t, rootDir, "payloads/payloads.go", string(source))

	got, count, err := renderPayloadsTS(rootDir)
	if err != nil {
		t.Fatalf("render payloads: %v", err)
	}
	if count != 7 {
		t.Fatalf("type count = %d, want 7\n%s", count, got)
	}
	for _, name := range []string{
		"ConfirmationPayload",
		"LoginPayload",
		"PasswordResetPageProps",
		"PasswordResetPayload",
		"PasswordResetRequestPayload",
		"RegistrationPayload",
		"WelcomeProps",
	} {
		if !strings.Contains(string(got), "export type "+name+" = {") {
			t.Fatalf("missing generated type %s in:\n%s", name, got)
		}
	}

	pages, err := fs.Glob(layouttemplates.Files, "inertia_*pages_auth_*.tmpl")
	if err != nil {
		t.Fatalf("glob auth pages: %v", err)
	}
	if len(pages) != 15 {
		t.Fatalf("auth page templates = %d, want 15 (5 per adapter)", len(pages))
	}
	for _, page := range pages {
		contents, err := fs.ReadFile(layouttemplates.Files, page)
		if err != nil {
			t.Fatalf("read %s: %v", page, err)
		}
		_, rest, found := strings.Cut(string(contents), "useForm<")
		if !found {
			t.Errorf("%s: useForm is not typed with a generated payload", page)
			continue
		}
		name, _, _ := strings.Cut(rest, ">")
		if !strings.Contains(string(got), "export type "+name+" = {") {
			t.Errorf("%s: useForm<%s> has no generated payload type", page, name)
		}
		imported := false
		for line := range strings.SplitSeq(string(contents), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "import type {") &&
				strings.Contains(line, "@/types/payloads") &&
				strings.Contains(line, name) {
				imported = true
				break
			}
		}
		if !imported {
			t.Errorf("%s: missing type import for %s", page, name)
		}
	}
}

