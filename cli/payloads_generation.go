func controllerImportMap(file *ast.File) map[string]string {
	imports := map[string]string{}
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}
		name := filepath.Base(path)
		if spec.Name != nil {
			if spec.Name.Name == "_" || spec.Name.Name == "." {
				continue
			}
			name = spec.Name.Name
		}
		imports[name] = path
	}
	return imports
}

func controllerPkgFromImport(importPath string) string {
	if importPath == "" {
		return ""
	}
	idx := strings.Index(importPath, "/controllers")
	if idx == -1 {
		if filepath.Base(importPath) == "controllers" {
			return "controllers"
		}
		return ""
	}
	return strings.TrimPrefix(importPath[idx+1:], "/")
}

