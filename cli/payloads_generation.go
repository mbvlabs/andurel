func isInertiaFromStructCall(fun ast.Expr, imports map[string]string) bool {
	sel, ok := fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "FromStruct" {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	path := imports[ident.Name]
	if path == "" {
		return ident.Name == "inertia"
	}
	return strings.HasSuffix(path, "/inertia") || strings.HasSuffix(path, "/pkg/inertia")
}

func isBindCall(fun ast.Expr) bool {
	sel, ok := fun.(*ast.SelectorExpr)
	return ok && sel.Sel.Name == "Bind"
}

func collectFuncLocals(fn *ast.FuncDecl) map[string]ast.Expr {
	locals := map[string]ast.Expr{}
	ast.Inspect(fn.Body, func(node ast.Node) bool {
		switch typed := node.(type) {
		case *ast.AssignStmt:
			if typed.Tok != token.DEFINE {
				return true
			}
			for i, lhs := range typed.Lhs {
				ident, ok := lhs.(*ast.Ident)
				if !ok || ident.Name == "_" || i >= len(typed.Rhs) {
					continue
				}
				locals[ident.Name] = typed.Rhs[i]
			}
		case *ast.ValueSpec:
			for i, name := range typed.Names {
				if typed.Type != nil {
					locals[name.Name] = typed.Type
					continue
				}
				if i < len(typed.Values) {
					locals[name.Name] = typed.Values[i]
				}
			}
		}
		return true
	})
	return locals
}

func pointerIdent(expr ast.Expr) (string, bool) {
	unary, ok := expr.(*ast.UnaryExpr)
	if !ok {
		return "", false
	}
	ident, ok := unary.X.(*ast.Ident)
	if !ok {
		return "", false
	}
	return ident.Name, true
}

func isAnonymousStruct(expr ast.Expr) bool {
	expr = unwrapStar(expr)
	if unary, ok := expr.(*ast.UnaryExpr); ok {
		expr = unwrapStar(unary.X)
	}
	if lit, ok := expr.(*ast.CompositeLit); ok {
		expr = lit.Type
	}
	_, ok := expr.(*ast.StructType)
	return ok
}

func unwrapStar(expr ast.Expr) ast.Expr {
	for {
		switch typed := expr.(type) {
		case *ast.StarExpr:
			expr = typed.X
		case *ast.ParenExpr:
			expr = typed.X
		default:
			return expr
		}
	}
}

func namedStructRefs(expr ast.Expr) []ast.Expr {
	var refs []ast.Expr
	var walk func(ast.Expr)
	walk = func(e ast.Expr) {
		switch typed := e.(type) {
		case *ast.StarExpr:
			walk(typed.X)
		case *ast.ArrayType:
			walk(typed.Elt)
		case *ast.Ident:
			if ast.IsExported(typed.Name) {
				refs = append(refs, typed)
			}
		case *ast.SelectorExpr:
			refs = append(refs, typed)
		}
	}
	walk(expr)
	return refs
}

func jsonFieldMeta(field *ast.Field) (name string, include bool, omitempty bool) {
	if field.Tag == nil {
		if len(field.Names) == 1 {
			return field.Names[0].Name, true, false
		}
		return "", true, false
	}
	tag, err := strconv.Unquote(field.Tag.Value)
	if err != nil {
		return "", true, false
	}
	jsonTag := reflect.StructTag(tag).Get("json")
	if jsonTag == "" {
		if len(field.Names) == 1 {
			return field.Names[0].Name, true, false
		}
		return "", true, false
	}
	name, opts, _ := strings.Cut(jsonTag, ",")
	if name == "-" {
		return "", false, false
	}
	return name, true, strings.Contains(","+opts+",", ",omitempty,")
}

func fieldIdent(field *ast.Field) string {
	if len(field.Names) == 0 {
		return "(embedded)"
	}
	return field.Names[0].Name
}

func exprString(expr ast.Expr) string {
	switch typed := expr.(type) {
	case *ast.Ident:
		return typed.Name
	case *ast.SelectorExpr:
		return exprString(typed.X) + "." + typed.Sel.Name
	case *ast.StarExpr:
		return "*" + exprString(typed.X)
	case *ast.ArrayType:
		return "[]" + exprString(typed.Elt)
	case *ast.MapType:
		return "map[" + exprString(typed.Key) + "]" + exprString(typed.Value)
	default:
		return fmt.Sprintf("%T", expr)
	}
}

func mapBuiltinIdent(name string) (string, bool) {
	switch name {
	case "bool":
		return "boolean", true
	case "string":
		return "string", true
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64",
		"float32", "float64", "byte", "rune":
		return "number", true
	default:
		return "", false
	}
}

func mapKnownSelector(importPath, pkgName, typeName string) (string, bool, bool) {
	switch {
	case typeName == "UUID" && (pkgName == "uuid" || strings.HasSuffix(importPath, "uuid")):
		return "string", false, true
	case typeName == "Time" && (pkgName == "time" || strings.HasSuffix(importPath, "time")):
		return "string", false, true
	case typeName == "RawMessage" && (pkgName == "json" || strings.HasSuffix(importPath, "json")):
		return "JsonValue", true, true
	}
	if pkgName == "sql" || strings.HasSuffix(importPath, "database/sql") {
		if mapped, ok := mapSQLNull(typeName); ok {
			return mapped + " | null", false, true
		}
	}
	if pkgName == "pgtype" || strings.HasSuffix(importPath, "pgtype") {
		if mapped, usedJSON, ok := mapPGType(typeName); ok {
			return mapped + " | null", usedJSON, true
		}
	}
	return "", false, false
}

func mapSQLNull(name string) (string, bool) {
	switch name {
	case "NullString":
		return "string", true
	case "NullBool":
		return "boolean", true
	case "NullInt16", "NullInt32", "NullInt64", "NullFloat64", "NullByte":
		return "number", true
	case "NullTime":
		return "string", true
	default:
		return "", false
	}
}

func mapPGType(name string) (string, bool, bool) {
	switch name {
	case "Text":
		return "string", false, true
	case "Bool":
		return "boolean", false, true
	case "Int2", "Int4", "Int8", "Float4", "Float8":
		return "number", false, true
	case "Numeric", "UUID", "Date", "Time", "Timestamp", "Timestamptz", "Bytea":
		return "string", false, true
	case "JSON", "JSONB":
		return "JsonValue", true, true
	default:
		return "", false, false
	}
}
