const (
	generatedEmailsDir          = "emails/_generated"
	generatedEmailsPropsTSPath  = generatedEmailsDir + "/props.ts"
	generatedEmailsManifestPath = generatedEmailsDir + "/manifest.ts"
)

const generatedEmailsHeader = "// Code generated by andurel sync emails; DO NOT EDIT.\n"

type emailsReport struct {
	GeneratedFiles []string `json:"generated_files"`
	TemplateCount  int      `json:"template_count"`
	Exported       bool     `json:"exported"`
}

type emailStructDecl struct {
	name       string
	sourceFile string
	line       int
	structType *ast.StructType
}

type emailTemplate struct {
	goName    string
	snakeName string
	kebabName string
	fields    []emailTemplateField
}

type emailTemplateField struct {
	goName string
	tsType string
}

type emailScan struct {
	rootDir     string
	fset        *token.FileSet
	structs     map[string]*emailStructDecl
	htmlMethods map[string]bool
}

func newGenerateEmailsCommand() *cobra.Command {
	var skipExport bool
	cmd := &cobra.Command{
		Use:   "emails",
		Short: "Generate TypeScript email props and export Go email templates",
		Long: `Generate the typed React Email props and export the Go email templates.

Every exported struct in email/*.go that declares ToHTML() (string, error) is
emitted. Scalar fields become TypeScript values: string stays string, integers
and float64 become number | string so a component can take real numbers from
fixture data and generated Go template placeholders. Slices, maps, bools, structs,
pointers and interfaces are a generation error: format them into a string
field in Go, because emails support scalar fields only.

It writes emails/_generated/props.ts with <Name>Props, <Name>HtmlVars and
<Name>TextVars, and emails/_generated/manifest.ts consumed by emails/_export.tsx.
It then runs the project's email:export script, which writes the committed
email/templates/*.tmpl files. Run it after changing email/*.go or emails/**.`,
		Example: `  andurel sync emails
  andurel sync emails --skip-export
  andurel sync emails --json`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			rootDir, err := findGoModRoot()
			if err != nil {
				return err
			}
			if err := requireInertiaProjectForRoutesJS(rootDir); err != nil {
				return err
			}
			opts, err := output.ParseOptions(cmd)
			if err != nil {
				return err
			}
			report, err := generateEmailsFiles(rootDir)
			if err != nil {
				return err
			}
			if !skipExport {
				exportOut := cmd.OutOrStdout()
				if output.UsesStructuredOutput(opts) {
					exportOut = cmd.ErrOrStderr()
				}
				if err := runEmailsExport(
					cmd.Context(),
					rootDir,
					exportOut,
					cmd.ErrOrStderr(),
				); err != nil {
					return err
				}
				report.Exported = true
			}
			return output.OK(cmd, report, emailsReportSummary(report))
		},
	}
	cmd.Flags().
		BoolVar(&skipExport, "skip-export", false, "Only write emails/_generated; do not run the email:export script")
	setAgentMetadata(
		cmd,
		"generation",
		"Writes emails/_generated/props.ts and emails/_generated/manifest.ts from exported email/*.go structs with a ToHTML method, then runs the project's email:export script to regenerate email/templates/*.tmpl. Use --skip-export when frontend dependencies are not installed. Use --json for generated files, template count and whether the export ran.",
	)
	return cmd
}

func emailsReportSummary(report emailsReport) string {
	summary := fmt.Sprintf(
		"Generated %d email templates to %s",
		report.TemplateCount,
		generatedEmailsDir,
	)
	if report.Exported {
		summary += " and exported email/templates"
	}
	return summary
}

// hasReactEmails reports whether the project carries the React Email
// authoring scaffold. Older scaffolds without emails/ keep the Go-only email
// path.
func hasReactEmails(rootDir string) bool {
	info, err := os.Stat(filepath.Join(rootDir, "emails"))
	return err == nil && info.IsDir()
}

// runEmailsExport runs the project's email:export script through its recorded
// package manager. It requires installed frontend dependencies because the
// script imports react-email and tsx from node_modules.
func runEmailsExport(ctx context.Context, rootDir string, stdout, stderr io.Writer) error {
	packageManager := frontendPackageManager(rootDir)
	nodeModules := filepath.Join(rootDir, "node_modules")
	if info, err := os.Stat(nodeModules); err != nil || !info.IsDir() {
		return output.NewError(
			output.CodeMissingTool,
			"frontend dependencies are not installed",
			output.ExitDependency,
			"Run '"+packageManager+" install', then run andurel sync emails again. "+
				"Use --skip-export to write emails/_generated only.",
		)
	}

	exportCmd := exec.CommandContext(ctx, packageManager, "run", "email:export")
	exportCmd.Dir = rootDir
	exportCmd.Stdout = stdout
	exportCmd.Stderr = stderr
	if err := exportCmd.Run(); err != nil {
		return output.WrapError(
			output.CodeExternalCommandFailed,
			fmt.Errorf("%s run email:export failed: %w", packageManager, err),
			output.ExitExternal,
			"Fix the React Email export error above, then run andurel sync emails again.",
		)
	}
	return nil
}

func generateEmailsFiles(rootDir string) (emailsReport, error) {
	props, manifest, count, err := renderEmailsTS(rootDir)
	if err != nil {
		return emailsReport{}, err
	}
	files := []struct {
		path    string
		content []byte
	}{
		{path: generatedEmailsManifestPath, content: manifest},
		{path: generatedEmailsPropsTSPath, content: props},
	}
	for _, file := range files {
		target := filepath.Join(rootDir, filepath.FromSlash(file.path))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return emailsReport{}, err
		}
		if err := os.WriteFile(target, file.content, 0o644); err != nil {
			return emailsReport{}, err
		}
	}
	return emailsReport{
		GeneratedFiles: []string{generatedEmailsManifestPath, generatedEmailsPropsTSPath},
		TemplateCount:  count,
	}, nil
}

func renderEmailsTS(rootDir string) ([]byte, []byte, int, error) {
	templates, err := scanEmails(rootDir)
	if err != nil {
		return nil, nil, 0, err
	}
	return renderEmailsPropsTS(templates),
		renderEmailsManifestTS(templates),
		len(templates),
		nil
}

func scanEmails(rootDir string) ([]emailTemplate, error) {
	emailDir := filepath.Join(rootDir, "email")
	entries, err := os.ReadDir(emailDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, generationFailed(
				"email directory not found",
				"Create email/*.go with an exported struct that declares ToHTML() (string, error).",
			)
		}
		return nil, fmt.Errorf("read email directory: %w", err)
	}

	scan := &emailScan{
		rootDir:     rootDir,
		fset:        token.NewFileSet(),
		structs:     map[string]*emailStructDecl{},
		htmlMethods: map[string]bool{},
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") ||
			strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		if err := scan.parseFile(filepath.Join(emailDir, entry.Name())); err != nil {
			return nil, err
		}
	}

	names := make([]string, 0, len(scan.structs))
	for name := range scan.structs {
		names = append(names, name)
	}
	slices.Sort(names)

	templates := make([]emailTemplate, 0, len(names))
	for _, name := range names {
		if !scan.htmlMethods[name] {
			continue
		}
		structure := scan.structs[name]
		fields, err := scan.emailFields(structure)
		if err != nil {
			return nil, err
		}
		template := emailTemplate{
			goName:    name,
			snakeName: naming.ToSnakeCase(name),
			fields:    fields,
		}
		template.kebabName = naming.ToKebabCase(template.snakeName)
		templates = append(templates, template)
	}
	slices.SortFunc(templates, func(a, b emailTemplate) int {
		return strings.Compare(a.snakeName, b.snakeName)
	})

	seen := map[string]string{}
	for _, template := range templates {
		if existing, ok := seen[template.snakeName]; ok {
			return nil, generationFailed(
				fmt.Sprintf(
					"email types %s and %s both map to template %q",
					existing,
					template.goName,
					template.snakeName,
				),
				"Rename one Go type so each email has a unique snake_case template name.",
			)
		}
		seen[template.snakeName] = template.goName
	}

	return templates, nil
}

func (s *emailScan) parseFile(path string) error {
	file, err := parser.ParseFile(s.fset, path, nil, parser.SkipObjectResolution)
	if err != nil {
		return fmt.Errorf("parse email file %s: %w", path, err)
	}
	if file.Name.Name != "email" {
		return generationFailed(
			fmt.Sprintf("%s: package %s; email structs belong in package email", path, file.Name.Name),
			"Move the declaration to email/ and declare package email.",
		)
	}
	sourceFile := routeManifestSourceFile(s.rootDir, path)

	for _, decl := range file.Decls {
		switch typed := decl.(type) {
		case *ast.GenDecl:
			if typed.Tok != token.TYPE {
				continue
			}
			for _, spec := range typed.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok || !ast.IsExported(typeSpec.Name.Name) {
					continue
				}
				structType, ok := typeSpec.Type.(*ast.StructType)
				if !ok {
					continue
				}
				name := typeSpec.Name.Name
				if existing, ok := s.structs[name]; ok {
					return generationFailed(
						fmt.Sprintf(
							"email type %s is declared twice: %s and %s",
							name,
							existing.sourceFile,
							sourceFile,
						),
						"Keep one declaration per email type name.",
					)
				}
				s.structs[name] = &emailStructDecl{
					name:       name,
					sourceFile: sourceFile,
					line:       s.fset.Position(typeSpec.Pos()).Line,
					structType: structType,
				}
			}
		case *ast.FuncDecl:
			if typed.Recv == nil || typed.Name.Name != "ToHTML" {
				continue
			}
			receiver, ok := emailReceiverTypeName(typed.Recv)
			if !ok || !isEmailToHTMLSignature(typed.Type) {
				continue
			}
			s.htmlMethods[receiver] = true
		}
	}
	return nil
}

func emailReceiverTypeName(recv *ast.FieldList) (string, bool) {
	if recv == nil || len(recv.List) != 1 {
		return "", false
	}
	return emailIdentName(recv.List[0].Type)
}

func emailIdentName(expr ast.Expr) (string, bool) {
	switch typed := expr.(type) {
	case *ast.Ident:
		return typed.Name, true
	case *ast.StarExpr:
		return emailIdentName(typed.X)
	case *ast.ParenExpr:
		return emailIdentName(typed.X)
	case *ast.IndexExpr:
		return emailIdentName(typed.X)
	case *ast.IndexListExpr:
		return emailIdentName(typed.X)
	default:
		return "", false
	}
}

func isEmailToHTMLSignature(fn *ast.FuncType) bool {
	if fn.Params != nil && len(fn.Params.List) > 0 {
		return false
	}
	if fn.Results == nil || len(fn.Results.List) != 2 {
		return false
	}
	first, ok := emailIdentName(fn.Results.List[0].Type)
	if !ok || first != "string" {
		return false
	}
	second, ok := emailIdentName(fn.Results.List[1].Type)
	return ok && second == "error"
}

func (s *emailScan) emailFields(structure *emailStructDecl) ([]emailTemplateField, error) {
	if structure.structType.Fields == nil {
		return nil, nil
	}
	fields := make([]emailTemplateField, 0, len(structure.structType.Fields.List))
	for _, field := range structure.structType.Fields.List {
		if len(field.Names) == 0 {
			return nil, unsupportedEmailField(
				structure,
				exprString(field.Type),
				"(embedded)",
			)
		}
		for _, ident := range field.Names {
			if !ast.IsExported(ident.Name) {
				continue
			}
			tsType, ok := emailFieldType(field.Type)
			if !ok {
				return nil, unsupportedEmailField(
					structure,
					exprString(field.Type),
					ident.Name,
				)
			}
			fields = append(fields, emailTemplateField{
				goName: ident.Name,
				tsType: tsType,
			})
		}
	}
	return fields, nil
}

func unsupportedEmailField(
	structure *emailStructDecl,
	typeName, fieldName string,
) error {
	loc := fmt.Sprintf("%s:%d", structure.sourceFile, structure.line)
	return generationFailed(
		fmt.Sprintf(
			"%s: %s.%s has unsupported type %s",
			loc,
			structure.name,
			fieldName,
			typeName,
		),
		"Format it into a string field in Go (emails support scalar fields only).",
	)
}

func emailFieldType(expr ast.Expr) (string, bool) {
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return "", false
	}
	switch ident.Name {
	case "string":
		return "string", true
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"byte", "rune", "float64":
		// Placeholders are Go template strings at export time, while
		// fixture data can pass real numbers to the component.
		return "number | string", true
	default:
		return "", false
	}
}

func renderEmailsPropsTS(templates []emailTemplate) []byte {
	var buf bytes.Buffer
	buf.WriteString(generatedEmailsHeader)
	buf.WriteString("\n// Edit the structs in email/*.go, then run andurel sync emails.\n")
	if emailsHaveNumericFields(templates) {
		buf.WriteString(
			"// Numeric Go fields are number | string: fixture data passes a number,\n" +
				"// while the generated template vars carry Go placeholder strings.\n",
		)
	}
	for _, template := range templates {
		fmt.Fprintf(&buf, "\nexport type %sProps = {\n", template.goName)
		for _, field := range template.fields {
			fmt.Fprintf(&buf, "  %s: %s\n", renderPayloadFieldName(field.goName), field.tsType)
		}
		buf.WriteString("}\n")

		fmt.Fprintf(
			&buf,
			"\nexport const %sHtmlVars: %sProps = {\n",
			template.goName,
			template.goName,
		)
		for _, field := range template.fields {
			fmt.Fprintf(
				&buf,
				"  %s: \"{{.%s | html}}\",\n",
				renderPayloadFieldName(field.goName),
				field.goName,
			)
		}
		buf.WriteString("}\n")

		fmt.Fprintf(
			&buf,
			"\nexport const %sTextVars: %sProps = {\n",
			template.goName,
			template.goName,
		)
		for _, field := range template.fields {
			fmt.Fprintf(
				&buf,
				"  %s: \"{{.%s}}\",\n",
				renderPayloadFieldName(field.goName),
				field.goName,
			)
		}
		buf.WriteString("}\n")
	}
	return buf.Bytes()
}

func emailsHaveNumericFields(templates []emailTemplate) bool {
	for _, template := range templates {
		for _, field := range template.fields {
			if field.tsType != "string" {
				return true
			}
		}
	}
	return false
}

func renderEmailsManifestTS(templates []emailTemplate) []byte {
	var buf bytes.Buffer
	buf.WriteString(generatedEmailsHeader)
	buf.WriteString("\n")
	buf.WriteString("import type { ComponentType } from \"react\"\n")
	for _, template := range templates {
		fmt.Fprintf(
			&buf,
			"import %s from \"../%s\"\n",
			template.goName,
			template.kebabName,
		)
	}
	if len(templates) > 0 {
		buf.WriteString("import type {\n")
		for _, template := range templates {
			fmt.Fprintf(&buf, "  %sProps,\n", template.goName)
		}
		buf.WriteString("} from \"./props\"\n")
		buf.WriteString("import {\n")
		for _, template := range templates {
			fmt.Fprintf(&buf, "  %sHtmlVars,\n", template.goName)
			fmt.Fprintf(&buf, "  %sTextVars,\n", template.goName)
		}
		buf.WriteString("} from \"./props\"\n")
	}

	buf.WriteString(`
export type EmailManifestEntry = {
  name: string
  component: ComponentType<any>
  htmlVars: Record<string, unknown>
  textVars: Record<string, unknown>
}
`)
	for _, template := range templates {
		varName := naming.ToLowerCamelCase(template.goName) + "Template"
		fmt.Fprintf(&buf, "\nconst %s = {\n", varName)
		fmt.Fprintf(&buf, "  name: %q,\n", template.snakeName)
		fmt.Fprintf(&buf, "  component: %s,\n", template.goName)
		fmt.Fprintf(&buf, "  htmlVars: %sHtmlVars,\n", template.goName)
		fmt.Fprintf(&buf, "  textVars: %sTextVars,\n", template.goName)
		buf.WriteString("} satisfies {\n")
		buf.WriteString("  name: string\n")
		fmt.Fprintf(&buf, "  component: ComponentType<%sProps>\n", template.goName)
		fmt.Fprintf(&buf, "  htmlVars: %sProps\n", template.goName)
		fmt.Fprintf(&buf, "  textVars: %sProps\n", template.goName)
		buf.WriteString("}\n")
	}

	buf.WriteString("\nexport const emails: EmailManifestEntry[] = [\n")
	for _, template := range templates {
		fmt.Fprintf(&buf, "  %sTemplate,\n", naming.ToLowerCamelCase(template.goName))
	}
	buf.WriteString("]\n")
	return buf.Bytes()
}
