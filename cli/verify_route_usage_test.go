const generatedRoutesFixture = `// Code generated by andurel; DO NOT EDIT.
type HostOrigins = Record<string, string>

let origins: HostOrigins = {}

export function configureRouteHosts(next: HostOrigins) {
  origins = next
}

function origin(host: string): string {
  return origins[host] ?? origins.primary ?? ''
}

export const routes = {
  homePage: routeHelper({ host: 'primary', path: () => '/' }),
  userShow: routeHelper({ host: 'primary', path: (id: number) => ` + "`/users/${id}`" + ` }),
}

function routeHelper<Args extends unknown[]>(def: {
  host: string
  path: (...args: Args) => string
}) {
  const full = (...args: Args) => origin(def.host) + def.path(...args)
  return Object.assign(full, {
    path: def.path,
    host: def.host,
  })
}
`

func writeRouteUsageFixture(t *testing.T, root, page string) {
	t.Helper()
	writeTestFile(t, root, generatedRoutesJSPath, generatedRoutesFixture)
	writeTestFile(t, root, "resources/js/Pages/Welcome.tsx", page)
}

func TestRouteUsageFlagsModuleInitializationCalls(t *testing.T) {
	tests := []struct {
		name     string
		page     string
		wantLine int
	}{
		{
			name: "module-scope constant",
			page: `import { routes } from '../routes'

export const cachedWelcome = routes.homePage()
`,
			wantLine: 3,
		},
		{
			name: "namespace alias",
			page: `import * as R from '../routes'

const cachedUser = R.userShow(7)
`,
			wantLine: 3,
		},
		{
			name: "named routes alias",
			page: `import { routes as appRoutes } from '../routes'

export const cached = appRoutes.homePage()
`,
			wantLine: 3,
		},
		{
			name: "eager exported array of objects",
			page: `import { routes } from '../routes'

export const links = [{ href: routes.homePage() }]
`,
			wantLine: 3,
		},
		{
			name: "module-scope object alias",
			page: `import { routes } from '../routes'

const r = routes
export const href = r.homePage()
`,
			wantLine: 4,
		},
		{
			name: "destructured helper",
			page: `import { routes } from '../routes'

const { homePage } = routes
export const href = homePage()
`,
			wantLine: 4,
		},
		{
			name: "local wrapper function",
			page: `import { routes } from '../routes'

function makeHome() {
  return routes.homePage()
}
export const href = makeHome()
`,
			wantLine: 6,
		},
		{
			name: "local arrow wrapper",
			page: `import { routes } from '../routes'

const makeHome = () => routes.homePage()
export const href = makeHome()
`,
			wantLine: 4,
		},
		{
			name: "template interpolation",
			page: `import { routes } from '../routes'

export const html = ` + "`" + `<a href="${routes.homePage()}">home</a>` + "`" + `
`,
			wantLine: 3,
		},
		{
			name: "immediately invoked arrow expression",
			page: `import { routes } from '../routes'

export const cached = (() => routes.homePage())()
`,
			wantLine: 3,
		},
		{
			name: "immediately invoked function expression",
			page: `import { routes } from '../routes'

export const cached = (function () {
  return routes.homePage()
})()
`,
			wantLine: 4,
		},
		{
			name: "bare module-scope call",
			page: `import { routes } from '../routes'

routes.homePage()
`,
			wantLine: 3,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeRouteUsageFixture(t, root, test.page)
			violations, skipped, applicable := analyzeRouteUsage(root)
			if !applicable || skipped != "" {
				t.Fatalf("route usage analysis skipped: applicable=%v reason=%q", applicable, skipped)
			}
			if len(violations) != 1 {
				t.Fatalf("violations = %#v, want one module-initialization call", violations)
			}
			violation := violations[0]
			if violation.Rule != "frontend-route-usage" ||
				violation.File != "resources/js/Pages/Welcome.tsx" ||
				violation.Line != test.wantLine {
				t.Fatalf("violation = %#v, want the page file and line %d", violation, test.wantLine)
			}
			if !strings.Contains(violation.Fix, ".path(") {
				t.Fatalf("fix = %q, want the .path() guidance", violation.Fix)
			}
		})
	}
}

func TestRouteUsageAllowsDeferredAndRelativeUsage(t *testing.T) {
	pages := map[string]string{
		"relative .path helper": `import { routes } from '../routes'
export const href = routes.homePage.path()
`,
		"helper host property": `import { routes } from '../routes'
export const host = routes.homePage.host
`,
		"deferred exported arrow": `import { routes } from '../routes'
export const makeHref = () => routes.homePage()
`,
		"arrow inside object literal": `import { routes } from '../routes'
export const links = [{ href: () => routes.homePage() }]
`,
		"component render body": `import { routes } from '../routes'

export default function Welcome() {
  const href = routes.homePage()
  return <a href={href}>Home</a>
}
`,
		"event handler": `import { routes } from '../routes'

export default function Welcome() {
  return <button onClick={() => routes.homePage()}>Home</button>
}
`,
		"named export function": `import { routes } from '../routes'

export function useHomeHref() {
  return routes.homePage()
}
`,
		"dynamic property access is outside the analysis": `import { routes } from '../routes'
const key = 'homePage'
export const href = (routes as any)[key]()
`,
		"unresolved alias is outside the analysis": `import { routes } from '@/lib/routes'
export const href = routes.homePage()
`,
	}
	for name, page := range pages {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			writeRouteUsageFixture(t, root, page)
			violations, skipped, applicable := analyzeRouteUsage(root)
			if !applicable || skipped != "" {
				t.Fatalf("route usage analysis skipped: applicable=%v reason=%q", applicable, skipped)
			}
			if len(violations) != 0 {
				t.Fatalf("violations = %#v, want deferred/relative usage allowed", violations)
			}
		})
	}
}

func TestRouteUsageResolvesTsconfigPathAliases(t *testing.T) {
	// The generated scaffold imports route helpers with the @/ alias. Without
	// alias resolution this rule would silently analyze almost nothing.
	const tsconfig = `{
  "compilerOptions": {
    // generated scaffold alias
    "paths": {
      "@/*": ["./resources/js/*"],
    },
  },
}
`
	tests := []struct {
		name     string
		page     string
		wantLine int
	}{
		{
			name: "alias namespace",
			page: `import { routes } from '@/routes'

export const href = routes.homePage()
`,
			wantLine: 3,
		},
		{
			name: "alias named helper",
			page: `import { homePage } from '@/routes'

export const href = homePage()
`,
			wantLine: 3,
		},
		{
			name: "alias star namespace",
			page: `import * as R from '@/routes'

export const href = R.userShow(7)
`,
			wantLine: 3,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeTestFile(t, root, "tsconfig.json", tsconfig)
			writeRouteUsageFixture(t, root, test.page)
			violations, skipped, applicable := analyzeRouteUsage(root)
			if !applicable || skipped != "" {
				t.Fatalf("route usage analysis skipped: applicable=%v reason=%q", applicable, skipped)
			}
			if len(violations) != 1 {
				t.Fatalf("violations = %#v, want the aliased module-initialization call", violations)
			}
			if violations[0].Line != test.wantLine {
				t.Fatalf("violation line = %d, want %d", violations[0].Line, test.wantLine)
			}
		})
	}
}

func TestLoadTsconfigPathAliasesParsesJSONC(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "tsconfig.json", `{
  // comments and trailing commas must not disable the rule
  "compilerOptions": {
    "baseUrl": ".",
    "paths": {
      "~/*": ["resources/js/*",],
    },
  },
}
`)
	aliases := loadTsconfigPathAliases(root)
	if len(aliases) != 1 || aliases[0].pattern != "~/*" || aliases[0].target != "resources/js/*" {
		t.Fatalf("aliases = %#v, want the ~/* mapping under resources/js", aliases)
	}
}

func TestVerifyRouteUsageRuleFailsAndPasses(t *testing.T) {
	root := newVerifyTestProject(t)
	writeRouteUsageFixture(t, root, `import { routes } from '../routes'

export const cachedWelcome = routes.homePage()
`)

	result := runVerifyInProject(
		t, root, "verify", "--only", "frontend", "--rules", "frontend-route-usage", "--json",
	)
	assertVerifyExitCode(t, result, output.ExitVerification)
	report, ok := output.Fail(result.err).Data.(verifyReport)
	if !ok {
		t.Fatalf("failure data = %T", output.Fail(result.err).Data)
	}
	step := findVerifyStep(t, report, "frontend")
	if step.Status != verifyStatusFail || len(step.Violations) != 1 {
		t.Fatalf("frontend step = %#v, want one route-usage violation", step)
	}
	violation := step.Violations[0]
	if violation.Rule != "frontend-route-usage" ||
		violation.File != "resources/js/Pages/Welcome.tsx" ||
		!strings.Contains(violation.Message, "module initialization") {
		t.Fatalf("violation = %#v", violation)
	}
	if step.Rules == nil || len(step.Rules.Executed) != 1 ||
		step.Rules.Executed[0] != "frontend-route-usage" {
		t.Fatalf("frontend rules = %#v, want frontend-route-usage executed", step.Rules)
	}

	writeRouteUsageFixture(t, root, `import { routes } from '../routes'

export default function Welcome() {
  return <a href={routes.homePage()}>Home</a>
}
`)
	green := runVerifyInProject(
		t, root, "verify", "--only", "frontend", "--rules", "frontend-route-usage", "--json",
	)
	if green.err != nil {
		t.Fatalf("verify with render-time usage: %v\n%s", green.err, green.stderr)
	}
}

func TestRouteUsageReportsMissingGeneratedRoutes(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "resources/js/App.ts", "export const app = true\n")

	violations, skipped, applicable := analyzeRouteUsage(root)
	if len(violations) != 0 {
		t.Fatalf("violations = %#v, want none", violations)
	}
	if !applicable || !strings.Contains(skipped, "routes.ts is missing") {
		t.Fatalf("skipped = %q applicable = %v, want a missing routes.ts reason", skipped, applicable)
	}

	notApplicable := t.TempDir()
	if _, _, applicable := analyzeRouteUsage(notApplicable); applicable {
		t.Fatalf("a project without resources/js should be not applicable")
	}
}
